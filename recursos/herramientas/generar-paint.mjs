// "rehacer" es "deshacer" dado vuelta
ICONOS.rehacer = ICONOS.deshacer.map((fila) => [...fila].reverse().join(''));

function aSvg(nombre, dibujo) {
  if (dibujo.length !== 16) throw new Error(`${nombre}: tiene ${dibujo.length} filas (tienen que ser 16)`);
  const rects = [];
  dibujo.forEach((fila, y) => {
    if (fila.length !== 16) throw new Error(`${nombre}: la fila ${y} tiene ${fila.length} letras (tienen que ser 16)`);
    // Junta los pixeles seguidos del mismo color en un solo rectángulo (archivo más chico)
    let x = 0;
    while (x < 16) {
      const letra = fila[x];
      let fin = x + 1;
      while (fin < 16 && fila[fin] === letra) fin++;
      if (letra !== '.') {
        const color = PALETA[letra];
        if (!color) throw new Error(`${nombre}: la letra "${letra}" no está en la paleta`);
        rects.push(`<rect x="${x}" y="${y}" width="${fin - x}" height="1" fill="${color}"/>`);
      }
      x = fin;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" shape-rendering="crispEdges">${rects.join('')}</svg>\n`;
}

mkdirSync(salida, { recursive: true });
for (const [nombre, dibujo] of Object.entries(ICONOS)) {
  writeFileSync(join(salida, `${nombre}.svg`), aSvg(nombre, dibujo));
}
console.log(`Listo: ${Object.keys(ICONOS).length} íconos en recursos/paint/iconos/`);
